# Download the SONiC BMC third-party patches into a local directory that
# kernel_build_*_sonic_bmc.sh can use as --third-party-patches.
#
# Where the patches live
# ----------------------
# sonic-linux-kernel does not keep the kernel patches in patch/. That
# directory is only kconfig include/exclude lists. The patches themselves
# are files under patches-sonic/, and patches-sonic/series is the apply
# order.
#
# Nexthop has two separate groups in that series. They are not one set.
#
#   # Nexthop patches
#     About 16 patches just after the Micas block: AMD reset-reason
#     backports, xilinx SPI, Fintek 8250, and i2c-xiic. This is Nexthop's
#     x86 switch platform. It is not the BMC third-party layer, and this
#     script does not download it.
#
#   ###-> aspeed .. ###-> aspeed-end
#     Mixed vendor BMC patches at the end of the series. Nexthop authors
#     (chander@, jack@nexthop.ai) are only:
#       0001-aspeed-ast2700-support.patch
#       0002-aspeed-ast2700-*.patch          SDK drop; the suffix differs
#       0003-aspeed-ast2700-*.patch          by tree (00.07.02 vs 00.07.04)
#       aspeed-spi-txrx-fix-full-duplex-capture.patch   6.12.94 tree only
#       nexthop-b27-dts.patch
#       serial-8250_aspeed-fix-UDMA-ring-pointer-desync.patch
#       soc-aspeed-udma-lower-idle-timeout.patch
#     The three ast2700 patches are generic AST2700 support, generated by
#     scripts/generate-aspeed-patch.sh. nexthop-b27-dts is the B27 board.
#     Nokia, Arista Goldfinch, and Micas DTS in the same marker are other
#     vendors. The two mmc-sdhci-of-aspeed patches on 202608 are Aspeed
#     (cool_lee@aspeedtech.com); on 6.12.94 they are folded into 0001.
#
#   0001-DTS-Aspeed-Nvidia-spc6-a1-bmc-dts.patch
#   0002-DTS-Aspeed-Nvidia-spc6-bmc-dts.patch
#     NVIDIA (oivantsiv@nvidia.com), also inside ###-> aspeed. Not Nexthop.
#     Patch_BMC_Status_Table.txt edits aspeed-nvidia-spc6-bmc.dts, which
#     these two patches create, so the default BMC set keeps them.
#     Their Makefile hunks do not depend on the Nokia/Arista/Micas hunks.
#
#   ###-> nvidia_aspeed_bmc-start .. -end
#     Same names as Patch_BMC_Status_Table.txt. Layer 3 of the build.
#     Do not put them in this directory.
#
# Two trees matter:
#
#   --tree 202608
#     https://github.com/Azure/sonic-linux-kernel.msft branch 202608
#     Aspeed SDK v00.07.02. The branch Makefile defaults to kernel 6.12.41.
#
#   --tree 6.12.94   (default)
#     https://github.com/sonic-net/sonic-linux-kernel branch master
#     Aspeed SDK v00.07.04, regenerated for pristine 6.12.94.
#     0002/0003 filenames differ from the 202608 names above.
#
# The build applies, in order:
#   1. Patch_Status_Table.txt
#   2. this directory (series order)
#   3. Patch_BMC_Status_Table.txt
#
# A conflict fix is not added to the hw-mgmt series. Put the fixed file,
# under the same name, in
#   recipes-kernel/linux/linux-<major.minor>/third-party/<version>/
# The 6.x and 7.x build scripts use that copy instead of the download.
# Send the fix to SONiC.
#

set -euo pipefail

TREE="6.12.94"
REPO=""
REF=""
REPO_SET=0
REF_SET=0
DEST=""
FORCE=0
PRINT_ONLY=0
DRY_RUN=0
INCLUDE_NVIDIA=0
LIST_FILE=""
SECTIONS=()
SECTION_SET=0
SET="bmc"
SET_EXPLICIT=0

info() {
    printf '==> %s\n' "$*" >&2
}

die() {
    printf 'error: %s\n' "$*" >&2
    exit 1
}

usage() {
    cat <<EOF
Usage:
  ${0##*/} [options] <dest_dir>
  ${0##*/} --print [options]

Download the BMC third-party patches from SONiC patches-sonic/series into
<dest_dir>, and write <dest_dir>/series in series order.
kernel_build_*_sonic_bmc.sh reads that series when the directory is passed
as --third-party-patches.

The default set is the Nexthop-authored files inside ###-> aspeed, plus the
two NVIDIA SPC6 BMC DTS patches that Patch_BMC_Status_Table.txt edits.
It does not take the whole aspeed marker (Nokia, Arista, Micas, Aspeed mmc
backports) and it does not take the x86 "# Nexthop patches" block.

Options:
  -h, --help
  --tree SPEC      6.12.94 (default) or 202608.
                   6.12.94: sonic-net/sonic-linux-kernel master,
                            Aspeed v00.07.04 regenerated for 6.12.94.
                   202608:  Azure/sonic-linux-kernel.msft branch 202608,
                            Aspeed v00.07.02 (kernel default 6.12.41).
  --repo URL       GitHub repo instead of the --tree preset.
                   https://github.com/<owner>/<name>.git
  --ref NAME       Branch, tag, or commit instead of the --tree preset.
  --set NAME       bmc (default), nexthop, or aspeed.
                   bmc:     Nexthop AST2700 / Aspeed-driver patches in the
                            aspeed marker, plus the two NVIDIA SPC6 DTS
                            patches. aspeed-spi-txrx is included on trees
                            that have it.
                   nexthop: the Nexthop files only, no SPC6 DTS.
                   aspeed:  every patch in ###-> aspeed .. aspeed-end.
                   Ignored when --list or --section is set.
  --section NAME   Series marker to extract, instead of --set. Repeatable.
                   aspeed-upstream is the three SDK files on the 6.12.94 tree.
  --list FILE      Use these patch paths (relative to patches-sonic/) instead
                   of --set. Comments and blank lines are ignored.
  --include-nvidia Also append the nvidia_aspeed_bmc section.
                   Those patches are already applied from
                   Patch_BMC_Status_Table.txt. Leave this off for the
                   three-layer BMC build.
  --print          Print the selected patch names and exit.
  --dry-run        Resolve the list and print download URLs. Write nothing.
  --force          Replace an existing non-empty dest_dir.

Example, 6.12.94 BMC build:
  ${0##*/} /tmp/sonic-aspeed-patches
  kernel_build_6_x_sonic_bmc.sh /tmp/bmc-build /path/to/hw-mgmt 6.12.94 \\
      --third-party-patches /tmp/sonic-aspeed-patches

Nexthop files only, from the 202608 tree:
  ${0##*/} --tree 202608 --set nexthop /tmp/sonic-aspeed-patches

Every patch in the aspeed marker, including other vendors' DTS:
  ${0##*/} --set aspeed /tmp/sonic-aspeed-patches
EOF
}

trim() {
    local s=$1
    s=${s//$'\r'/}
    s=${s#"${s%%[![:space:]]*}"}
    s=${s%"${s##*[![:space:]]}"}
    printf '%s\n' "$s"
}

apply_tree() {
    case "$1" in
        6.12.94|master)
            REPO="https://github.com/sonic-net/sonic-linux-kernel.git"
            REF="master"
            ;;
        202608)
            REPO="https://github.com/Azure/sonic-linux-kernel.msft.git"
            REF="202608"
            ;;
        *)
            die "unknown --tree $1 (expected 6.12.94 or 202608)"
            ;;
    esac
}

github_slug() {
    local repo=$1
    repo=${repo%.git}
    repo=${repo#git@github.com:}
    repo=${repo#ssh://git@github.com/}
    repo=${repo#https://github.com/}
    repo=${repo#http://github.com/}
    [[ "$repo" == */* ]] || die "cannot parse GitHub repo from: $1"
    printf '%s\n' "$repo"
}

raw_url() {
    local path=$1
    printf 'https://raw.githubusercontent.com/%s/%s/%s\n' "$SLUG" "$SHA" "$path"
}

download() {
    local url=$1 dest=$2
    curl -fsSL --retry 5 --retry-delay 2 -o "$dest" "$url"
}

resolve_sha() {
    local sha line
    if [[ "$REF" =~ ^[0-9a-fA-F]{40}$ ]]; then
        SHA=$REF
        return
    fi
    line=$(git ls-remote "$REPO" "refs/heads/$REF" "refs/tags/$REF" "refs/tags/${REF}^{}")
    sha=$(printf '%s\n' "$line" | awk 'NF { print $1; exit }')
    [[ -n "$sha" ]] || die "ref not found in $REPO: $REF"
    SHA=$sha
}

# Print patch paths selected from a sonic series file on stdin.
select_sections() {
    local line marker section in_section name
    local -A wanted=()
    for section in "$@"; do
        wanted["$section"]=1
    done
    in_section=""
    while IFS= read -r line || [[ -n "$line" ]]; do
        line=$(trim "$line")
        [[ -z "$line" ]] && continue
        if [[ "$line" == '###->'* ]]; then
            marker=${line#\#\#\#->}
            marker=$(trim "$marker")
            if [[ -n "$in_section" && "$marker" == "${in_section}-end" ]]; then
                in_section=""
                continue
            fi
            # "###-> name" starts the section. "###-> name-start" is the
            # other form used in this series.
            if [[ -z "$in_section" && -n "${wanted[$marker]:-}" ]]; then
                in_section=$marker
                continue
            fi
            if [[ -z "$in_section" && "$marker" == *-start ]]; then
                section=${marker%-start}
                if [[ -n "${wanted[$section]:-}" ]]; then
                    in_section=$section
                fi
            fi
            continue
        fi
        [[ "$line" == \#* ]] && continue
        if [[ -n "$in_section" ]]; then
            name=${line%%[[:space:]]*}
            name=${name%%#*}
            [[ -n "$name" ]] && printf '%s\n' "$name"
        fi
    done
}

read_list_file() {
    local line name
    while IFS= read -r line || [[ -n "$line" ]]; do
        line=$(trim "$line")
        [[ -z "$line" || "$line" == \#* ]] && continue
        [[ "$line" == '###->'* ]] && continue
        name=${line%%[[:space:]]*}
        name=${name%%#*}
        [[ -n "$name" ]] && printf '%s\n' "$name"
    done <"$1"
}

# Globs for --set bmc and --set nexthop. Matched inside ###-> aspeed, in
# series order. 0002/0003 names differ between the 00.07.02 and 00.07.04 drops.
SET_GLOBS=()
SET_REQUIRED=()
SET_OPTIONAL=()

load_set_rules() {
    SET_GLOBS=(
        0001-aspeed-ast2700-support.patch
        '0002-aspeed-ast2700-*'
        '0003-aspeed-ast2700-*'
        aspeed-spi-txrx-fix-full-duplex-capture.patch
        nexthop-b27-dts.patch
        serial-8250_aspeed-fix-UDMA-ring-pointer-desync.patch
        soc-aspeed-udma-lower-idle-timeout.patch
    )
    SET_REQUIRED=(
        0001-aspeed-ast2700-support.patch
        '0002-aspeed-ast2700-*'
        '0003-aspeed-ast2700-*'
        nexthop-b27-dts.patch
        serial-8250_aspeed-fix-UDMA-ring-pointer-desync.patch
        soc-aspeed-udma-lower-idle-timeout.patch
    )
    SET_OPTIONAL=(aspeed-spi-txrx-fix-full-duplex-capture.patch)
    case "$1" in
        nexthop)
            ;;
        bmc)
            SET_GLOBS+=(
                0001-DTS-Aspeed-Nvidia-spc6-a1-bmc-dts.patch
                0002-DTS-Aspeed-Nvidia-spc6-bmc-dts.patch
            )
            SET_REQUIRED+=(
                0001-DTS-Aspeed-Nvidia-spc6-a1-bmc-dts.patch
                0002-DTS-Aspeed-Nvidia-spc6-bmc-dts.patch
            )
            ;;
        *)
            die "unknown --set $1 (expected bmc, nexthop, or aspeed)"
            ;;
    esac
}

# Keep series order. Patterns are matched with [[ == ]].
filter_names() {
    local name pattern
    for name in "$@"; do
        for pattern in "${SET_GLOBS[@]}"; do
            if [[ "$name" == $pattern ]]; then
                printf '%s\n' "$name"
                break
            fi
        done
    done
}

count_glob() {
    local pattern=$1 name hits=0
    shift
    for name in "$@"; do
        [[ "$name" == $pattern ]] && hits=$((hits + 1))
    done
    printf '%s\n' "$hits"
}

validate_set() {
    local pattern hits
    for pattern in "${SET_REQUIRED[@]}"; do
        hits=$(count_glob "$pattern" "$@")
        if [[ "$hits" -ne 1 ]]; then
            die "###-> aspeed has ${hits} matches for required ${pattern}"
        fi
    done
    for pattern in "${SET_OPTIONAL[@]}"; do
        hits=$(count_glob "$pattern" "$@")
        if [[ "$hits" -eq 0 ]]; then
            info "not on this tree: ${pattern}"
        elif [[ "$hits" -ne 1 ]]; then
            die "###-> aspeed has ${hits} matches for ${pattern}"
        fi
    done
}

while [[ $# -gt 0 ]]; do
    case "$1" in
        -h|--help)
            usage
            exit 0
            ;;
        --tree)
            [[ $# -ge 2 ]] || die "--tree needs a value"
            TREE=$2
            shift 2
            ;;
        --tree=*)
            TREE=${1#*=}
            shift
            ;;
        --repo)
            [[ $# -ge 2 ]] || die "--repo needs a value"
            REPO=$2
            REPO_SET=1
            shift 2
            ;;
        --repo=*)
            REPO=${1#*=}
            REPO_SET=1
            shift
            ;;
        --ref)
            [[ $# -ge 2 ]] || die "--ref needs a value"
            REF=$2
            REF_SET=1
            shift 2
            ;;
        --ref=*)
            REF=${1#*=}
            REF_SET=1
            shift
            ;;
        --set)
            [[ $# -ge 2 ]] || die "--set needs a value"
            SET=$2
            SET_EXPLICIT=1
            shift 2
            ;;
        --set=*)
            SET=${1#*=}
            SET_EXPLICIT=1
            shift
            ;;
        --section)
            [[ $# -ge 2 ]] || die "--section needs a value"
            SECTIONS+=("$2")
            SECTION_SET=1
            shift 2
            ;;
        --section=*)
            SECTIONS+=("${1#*=}")
            SECTION_SET=1
            shift
            ;;
        --list)
            [[ $# -ge 2 ]] || die "--list needs a file"
            LIST_FILE=$2
            shift 2
            ;;
        --list=*)
            LIST_FILE=${1#*=}
            shift
            ;;
        --include-nvidia)
            INCLUDE_NVIDIA=1
            shift
            ;;
        --print)
            PRINT_ONLY=1
            shift
            ;;
        --dry-run)
            DRY_RUN=1
            shift
            ;;
        --force)
            FORCE=1
            shift
            ;;
        --)
            shift
            break
            ;;
        -*)
            die "unknown option: $1"
            ;;
        *)
            [[ -z "$DEST" ]] || die "unexpected argument: $1"
            DEST=$1
            shift
            ;;
    esac
done
if [[ $# -gt 0 ]]; then
    [[ -z "$DEST" ]] || die "unexpected argument: $1"
    DEST=$1
    shift
    [[ $# -eq 0 ]] || die "unexpected argument: $1"
fi

user_repo=$REPO
user_ref=$REF
apply_tree "$TREE"
if [[ "$REPO_SET" -eq 1 && "$REF_SET" -eq 1 ]]; then
    REPO=$user_repo
    REF=$user_ref
elif [[ "$REPO_SET" -eq 1 || "$REF_SET" -eq 1 ]]; then
    die "--repo and --ref must be passed together"
fi

case "$SET" in
    bmc|nexthop|aspeed) ;;
    *) die "unknown --set $SET (expected bmc, nexthop, or aspeed)" ;;
esac
if [[ -n "$LIST_FILE" ]]; then
    [[ "$SECTION_SET" -eq 0 ]] || die "--list replaces --section"
    [[ "$SET_EXPLICIT" -eq 0 ]] || die "--list replaces --set"
    [[ "$INCLUDE_NVIDIA" -eq 0 ]] || die "--list replaces --include-nvidia"
    [[ -f "$LIST_FILE" ]] || die "list not found: $LIST_FILE"
elif [[ "$SECTION_SET" -eq 1 && "$SET_EXPLICIT" -eq 1 ]]; then
    die "--section replaces --set"
elif [[ "$SECTION_SET" -eq 1 && "$INCLUDE_NVIDIA" -eq 1 ]]; then
    already_nvidia=0
    for section in "${SECTIONS[@]}"; do
        [[ "$section" == nvidia_aspeed_bmc ]] && already_nvidia=1
    done
    [[ "$already_nvidia" -eq 1 ]] || SECTIONS+=(nvidia_aspeed_bmc)
fi

for section in "${SECTIONS[@]+"${SECTIONS[@]}"}"; do
    [[ "$section" =~ ^[A-Za-z0-9._-]+$ ]] || die "bad section name: $section"
done

if [[ "$PRINT_ONLY" -eq 0 && "$DRY_RUN" -eq 0 && -z "$DEST" ]]; then
    die "destination directory is required (or use --print)"
fi

need_cmd() {
    command -v "$1" >/dev/null 2>&1 || die "$1 is required"
}
need_cmd curl
need_cmd git
need_cmd awk

resolve_sha
SLUG=$(github_slug "$REPO")

info "repo: $SLUG"
info "ref:  $REF"
info "sha:  $SHA"

series_tmp=$(mktemp)
trap 'rm -f "$series_tmp"' EXIT
download "$(raw_url "patches-sonic/series")" "$series_tmp"

if [[ -n "$LIST_FILE" ]]; then
    mapfile -t PATCHES < <(read_list_file "$LIST_FILE")
    SELECT_NOTE="list: $LIST_FILE"
elif [[ "$SECTION_SET" -eq 1 || "$SET" == "aspeed" ]]; then
    if [[ "$SECTION_SET" -eq 0 ]]; then
        SECTIONS=(aspeed)
        if [[ "$INCLUDE_NVIDIA" -eq 1 ]]; then
            SECTIONS+=(nvidia_aspeed_bmc)
        fi
    fi
    mapfile -t PATCHES < <(select_sections "${SECTIONS[@]}" <"$series_tmp")
    SELECT_NOTE="sections: ${SECTIONS[*]}"
else
    load_set_rules "$SET"
    mapfile -t aspeed_names < <(select_sections aspeed <"$series_tmp")
    mapfile -t PATCHES < <(filter_names "${aspeed_names[@]+"${aspeed_names[@]}"}")
    validate_set "${PATCHES[@]+"${PATCHES[@]}"}"
    SELECT_NOTE="set: $SET"
    if [[ "$INCLUDE_NVIDIA" -eq 1 ]]; then
        mapfile -t nvidia_names < <(select_sections nvidia_aspeed_bmc <"$series_tmp")
        PATCHES+=("${nvidia_names[@]}")
        SELECT_NOTE="$SELECT_NOTE + nvidia_aspeed_bmc"
    fi
fi

if [[ ${#PATCHES[@]} -eq 0 ]]; then
    die "no patches selected (${SELECT_NOTE})"
fi

info "$SELECT_NOTE (${#PATCHES[@]} patches)"

if [[ "$PRINT_ONLY" -eq 1 ]]; then
    printf '%s\n' "${PATCHES[@]}"
    exit 0
fi

printf '  %s\n' "${PATCHES[@]}" >&2

if [[ "$DRY_RUN" -eq 1 ]]; then
    for name in "${PATCHES[@]}"; do
        printf '%s\n' "$(raw_url "patches-sonic/$name")"
    done
    exit 0
fi

if [[ -e "$DEST" && -n "$(ls -A "$DEST" 2>/dev/null || true)" ]]; then
    [[ "$FORCE" -eq 1 ]] || die "destination is not empty: $DEST (use --force)"
    find "$DEST" -mindepth 1 -maxdepth 1 -exec rm -rf {} +
fi
mkdir -p "$DEST"

for name in "${PATCHES[@]}"; do
    case "$name" in
        /*|*..*) die "refusing patch path: $name" ;;
    esac
    info "download $name"
    mkdir -p "$DEST/$(dirname "$name")"
    download "$(raw_url "patches-sonic/$name")" "$DEST/$name"
    if [[ ! -s "$DEST/$name" ]]; then
        die "empty download: $name"
    fi
done

{
    printf '# Fetched for kernel_build_*_sonic_bmc.sh --third-party-patches\n'
    printf '# repo: %s\n' "$REPO"
    printf '# ref: %s\n' "$REF"
    printf '# sha: %s\n' "$SHA"
    printf '# %s\n' "$SELECT_NOTE"
    printf '# Apply order is this file. kernel_build ignores comments.\n'
    printf '%s\n' "${PATCHES[@]}"
} >"$DEST/series"

info "wrote $DEST (${#PATCHES[@]} patches, series order)"
info "next: kernel_build_6_x_sonic_bmc.sh <build> <hw-mgmt> <kver> --third-party-patches $DEST"
